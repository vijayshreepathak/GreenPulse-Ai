import { useId } from "react";
import { Compass, Monitor, Moon, PlugZap, RotateCcw, Sparkles, Sun, Trash2 } from "lucide-react";
import { useCopilot } from "../../context/CopilotContext";
import { useTheme } from "../../context/ThemeContext";
import { usePreferences } from "../../context/PreferencesContext";
import { DATA_USE_NOTICE, describeAiStatus } from "../../lib/copilot";
import Dialog from "../common/Dialog";

function RadioGroup({ name, legend, value, onChange, options }) {
  return (
    <fieldset className="radio-cards">
      <legend>{legend}</legend>
      {options.map((option) => {
        const Icon = option.icon;
        return (
          <label key={option.value} className={`radio-card${value === option.value ? " is-checked" : ""}`}>
            <input type="radio" name={name} value={option.value} checked={value === option.value} onChange={() => onChange(option.value)} />
            {Icon && <Icon size={16} aria-hidden="true" />}
            <span>{option.label}</span>
          </label>
        );
      })}
    </fieldset>
  );
}

function Toggle({ label, description, checked, onChange }) {
  return (
    <label className="setting-toggle">
      <span>
        <strong>{label}</strong>
        <small>{description}</small>
      </span>
      <span className="switch">
        <input type="checkbox" role="switch" checked={checked} onChange={(event) => onChange(event.target.checked)} />
        <span className="switch__track" aria-hidden="true" />
      </span>
    </label>
  );
}

function CopilotSettings() {
  const copilot = useCopilot();
  const headingId = useId();
  const { status } = copilot;
  const summary = describeAiStatus(status);
  return (
    <section className="copilot-settings" aria-labelledby={headingId}>
      <h3 id={headingId}>
        <Sparkles size={16} aria-hidden="true" /> AI Copilot
      </h3>
      <Toggle
        label="Enable AI Copilot"
        description="Shows the Copilot button and lets you ask questions about the loaded data. Answers are generated by Google Gemini."
        checked={copilot.enabled}
        onChange={copilot.setEnabled}
      />
      {copilot.enabled ? (
        <>
          <dl className="copilot-settings__status">
            <div>
              <dt>Primary model</dt>
              <dd>{status.data?.model ?? (status.state === "error" ? "Unknown" : "Checking…")}</dd>
            </div>
            <div>
              <dt>Fallback model</dt>
              <dd>{status.data ? status.data.fallback_model || "None" : "—"}</dd>
            </div>
            {status.data?.last_answer?.model && (
              <div>
                <dt>Last answer from</dt>
                <dd>
                  {status.data.last_answer.model}
                  {status.data.last_answer.fallback_used && " (fallback)"}
                </dd>
              </div>
            )}
            <div>
              <dt>Provider status</dt>
              <dd>
                <span className={`copilot-status-dot copilot-status-dot--${summary.tone}`} aria-hidden="true" />
                {summary.label}
              </dd>
            </div>
          </dl>
          {summary.message && <p className="copilot-settings__note">{summary.message}</p>}
        </>
      ) : (
        <p className="copilot-settings__note">The Copilot is off: its button is hidden and no questions or page context are sent.</p>
      )}
      <p className="copilot-settings__note">{status.data?.data_use || DATA_USE_NOTICE}</p>
      <div className="copilot-settings__actions">
        {copilot.enabled && (
          <button type="button" className="button button--secondary button--sm" onClick={copilot.checkConnection} disabled={status.checking || !status.data?.available}>
            <PlugZap size={15} aria-hidden="true" /> {status.checking ? "Checking…" : "Check connection"}
          </button>
        )}
        <button type="button" className="button button--ghost button--sm" onClick={copilot.clearChat} disabled={!copilot.messages.length}>
          <Trash2 size={15} aria-hidden="true" /> Clear conversation
        </button>
      </div>
    </section>
  );
}

export default function SettingsDialog({ open, onClose, onStartTour }) {
  const { preference, setPreference, resetTheme } = useTheme();
  const { preferences, updatePreference, resetPreferences } = usePreferences();

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Settings"
      description="Stored only in this browser. No account or personal data is involved."
      footer={
        <>
          <button
            type="button"
            className="button button--ghost"
            onClick={() => {
              resetPreferences();
              resetTheme();
            }}
          >
            <RotateCcw size={15} aria-hidden="true" /> Reset local preferences
          </button>
          <button type="button" className="button button--primary" onClick={onClose}>Done</button>
        </>
      }
    >
      <RadioGroup
        name="theme"
        legend="Theme"
        value={preference}
        onChange={setPreference}
        options={[
          { value: "light", label: "Light", icon: Sun },
          { value: "dark", label: "Dark", icon: Moon },
          { value: "system", label: "System", icon: Monitor },
        ]}
      />
      <RadioGroup
        name="motion"
        legend="Motion"
        value={preferences.motion}
        onChange={(value) => updatePreference("motion", value)}
        options={[
          { value: "system", label: "Follow system" },
          { value: "reduce", label: "Reduce" },
          { value: "full", label: "Full" },
        ]}
      />
      <Toggle
        label="Background data refresh"
        description="Refresh modelled PM and the ranking about every 12 minutes while this tab is visible and online."
        checked={preferences.backgroundRefresh}
        onChange={(value) => updatePreference("backgroundRefresh", value)}
      />
      <Toggle
        label="Scroll-wheel map zoom"
        description="Turn off to scroll the page over the map without zooming."
        checked={preferences.mapScrollZoom}
        onChange={(value) => updatePreference("mapScrollZoom", value)}
      />
      <div className="setting-row">
        <span>
          <strong>Guided demo</strong>
          <small>A five-step introduction to the main views.</small>
        </span>
        <button
          type="button"
          className="button button--secondary button--sm"
          onClick={() => {
            onClose();
            onStartTour();
          }}
        >
          <Compass size={15} aria-hidden="true" /> Start tour
        </button>
      </div>
      <CopilotSettings />
    </Dialog>
  );
}

/**
 * Guided Insights: a rule-based assistant. Answers are assembled only from the loaded
 * datasets and the documented methodology. It is not a language model.
 */
import { contributions, extreme, inlineLabel, scoredZones, topDrivers, zoneLabel } from "./analysis";
import { AIR_QUALITY_LABEL, FACTORS, officialWeights } from "./constants";
import { describeAirQuality } from "./freshness";
import { formatNumber, formatPercent, toNumber } from "./numbers";

export const QUESTIONS = [
  { id: "top-zone", text: "Which zone needs the most attention?" },
  { id: "why-top", text: "Why does this zone rank first?" },
  { id: "largest-decline", text: "Which zone experienced the largest vegetation decline?" },
  { id: "lowest-tree", text: "Which zone has the lowest tree cover?" },
  { id: "lowest-green", text: "Which zone has the lowest green cover?" },
  { id: "plantable", text: "Where is plantable potential mapped?" },
  { id: "method", text: "How is the priority score calculated?" },
  { id: "pm-stress", text: "What does PM stress mean?" },
  { id: "sensors", text: "Are the air-quality readings from campus sensors?" },
  { id: "limitations", text: "What are the limitations of the current analysis?" },
  // Out of scope on purpose: answered with an explicit refusal, never with invented numbers.
  { id: "species", text: "Which tree species should be planted, and where?" },
  { id: "forecast", text: "What will the air quality be tomorrow?" },
];

const UNAVAILABLE = {
  status: "unavailable",
  summary: "This information is not available in the currently loaded data.",
  points: [],
  evidence: [],
};

function unavailable(title, reason) {
  return { ...UNAVAILABLE, title, points: reason ? [reason] : [] };
}

export function answerQuestion(id, context = {}) {
  const { priority = [], scoring = null, environment = null, cells = [] } = context;
  const zones = scoredZones(priority);
  const question = QUESTIONS.find((item) => item.id === id);
  const title = question?.text || "Unknown question";

  switch (id) {
    case "top-zone": {
      const top = zones[0];
      if (!top) return unavailable(title, "The official priority ranking has not loaded.");
      return {
        status: "answered",
        title,
        zoneId: top.zone_id,
        summary: `${zoneLabel(top)} has the highest official priority score: ${formatNumber(top.priority_score, 2)} (${top.priority_class}).`,
        points: zones.slice(0, 3).map((zone) => `#${zone.rank} ${zoneLabel(zone)} — ${formatNumber(zone.priority_score, 2)} (${zone.priority_class})`),
        evidence: [{ label: "Source", value: "Official zone ranking, rule-based score" }],
      };
    }
    case "why-top": {
      const [top, second] = zones;
      if (!top) return unavailable(title, "The official priority ranking has not loaded.");
      const parts = contributions(top).filter((item) => item.contribution !== null).sort((a, b) => b.contribution - a.contribution);
      const points = parts.map((item) => `${item.label}: component ${formatNumber(item.score, 1)} × weight ${formatNumber(officialWeights(scoring)[item.key] * 100, 0)}% = ${formatNumber(item.contribution, 2)} points`);
      let summary = `${zoneLabel(top)} totals ${formatNumber(top.priority_score, 2)} points. Its largest contributors are ${topDrivers(top, 2).map((item) => inlineLabel(item.label)).join(" and ")}.`;
      if (second) {
        const gaps = FACTORS.filter((factor) => factor.key !== "pm_stress")
          .map((factor) => ({ label: inlineLabel(factor.label), delta: (toNumber(top[factor.contributionField]) ?? 0) - (toNumber(second[factor.contributionField]) ?? 0) }))
          .sort((a, b) => b.delta - a.delta);
        summary += ` It leads ${zoneLabel(second)} by ${formatNumber(top.priority_score - second.priority_score, 2)} points, mostly through ${gaps[0].label} (+${formatNumber(gaps[0].delta, 2)}).`;
      }
      return {
        status: "answered",
        title,
        zoneId: top.zone_id,
        summary,
        points,
        evidence: [
          { label: "Reason generated by the scoring engine", value: top.reason },
          { label: "PM note", value: "Regional PM stress is identical for every zone and does not change relative order." },
        ],
      };
    }
    case "largest-decline": {
      const decline = extreme(zones, "ndvi_change", "min");
      if (!decline) return unavailable(title, "NDVI change could not be calculated from the historical records.");
      const record = decline.record;
      return {
        status: "answered",
        title,
        zoneId: record.zone_id,
        summary: decline.value < 0
          ? `${zoneLabel(record)} shows the largest Sentinel-2 NDVI decline: ${formatNumber(decline.value, 3, { signed: true })} from ${record.first_year} to ${record.latest_year}.`
          : `No zone shows a decline; the smallest change is ${formatNumber(decline.value, 3, { signed: true })} in ${zoneLabel(record)}.`,
        points: zones.map((zone) => `${zoneLabel(zone)}: ${formatNumber(zone.ndvi_change, 3, { signed: true })}`),
        evidence: [
          { label: "Baseline / latest NDVI", value: `${formatNumber(record.first_year_mean_ndvi, 3)} → ${formatNumber(record.latest_year_mean_ndvi, 3)}` },
          { label: "Source", value: "Sentinel-2 seasonal composites (same season each year)" },
          { label: "Interpretation limit", value: "NDVI change does not by itself identify the cause." },
        ],
      };
    }
    case "lowest-tree":
    case "lowest-green": {
      const field = id === "lowest-tree" ? "tree_percent" : "green_cover_percent";
      const label = id === "lowest-tree" ? "tree cover" : "green cover";
      const result = extreme(zones, field, "min");
      if (!result) return unavailable(title, `Zone ${label} values are not available.`);
      return {
        status: "answered",
        title,
        zoneId: result.record.zone_id,
        summary: `${zoneLabel(result.record)} has the lowest ${label}: ${formatPercent(result.value)}.`,
        points: [...zones].sort((a, b) => (toNumber(a[field]) ?? Infinity) - (toNumber(b[field]) ?? Infinity)).map((zone) => `${zoneLabel(zone)}: ${formatPercent(zone[field])}`),
        evidence: [{ label: "Source", value: id === "lowest-tree" ? "Dynamic World land cover (supporting indicator, ~10 m)" : "Sentinel-2 NDVI green-cover share (project-calibrated threshold)" }],
      };
    }
    case "plantable": {
      const items = (cells || []).map((feature) => feature?.properties || feature).filter(Boolean);
      if (!items.length) return unavailable(title, "The optional 50 m cell dataset is not loaded.");
      const positive = items.filter((cell) => (toNumber(cell.potential_plantable_percent) ?? 0) > 0);
      const byZone = positive.reduce((acc, cell) => ({ ...acc, [cell.zone_name || cell.zone_id]: (acc[cell.zone_name || cell.zone_id] || 0) + 1 }), {});
      return {
        status: "answered",
        title,
        summary: positive.length
          ? `${positive.length} of ${items.length} 50 m cells have a mapped plantable-potential share above zero.`
          : "No 50 m cell has mapped plantable potential above zero.",
        points: Object.entries(byZone).map(([zone, count]) => `${zone}: ${count} cell${count === 1 ? "" : "s"}`),
        evidence: [
          { label: "Source", value: "potential_plantable_percent, Dynamic World-derived 50 m grid" },
          { label: "Important", value: "A mapped cell is not a validated planting site; local ground review is required." },
        ],
      };
    }
    case "method": {
      const weights = officialWeights(scoring);
      return {
        status: "answered",
        title,
        summary: "The official score is a transparent weighted sum of five 0–100 component scores (rule-based, not machine learning), calculated per zone.",
        points: FACTORS.map((factor) => `${formatNumber(weights[factor.key] * 100, 0)}% × ${factor.label} = ${factor.formula}`),
        evidence: [
          { label: "Classes", value: "≤30 Low · ≤50 Moderate · ≤70 High · >70 Urgent" },
          { label: "PM fallback", value: `${formatNumber(scoring?.pm?.fallback_score ?? 60, 0)} when no usable modelled PM data exists` },
        ],
      };
    }
    case "pm-stress": {
      const state = describeAirQuality(environment);
      const avg = environment?.averages_24h || {};
      const components = environment?.stress_components || {};
      const stress = toNumber(environment?.stress_score);
      return {
        status: stress === null ? "unavailable" : "answered",
        title,
        summary: "PM stress is a project-specific 0–100 normalisation of recent modelled PM2.5 and PM10. It is not an official regulatory AQI.",
        points: [
          `PM2.5 score = min(24-h mean ÷ 60 × 100, 100); PM10 score = min(24-h mean ÷ 100 × 100, 100).`,
          `PM stress = 0.6 × PM2.5 score + 0.4 × PM10 score.`,
          stress === null
            ? "No PM stress value is currently loaded."
            : `Current: PM2.5 mean ${formatNumber(avg.pm2_5, 1)} µg/m³ → ${formatNumber(components.pm25_score, 1)}; PM10 mean ${formatNumber(avg.pm10, 1)} µg/m³ → ${formatNumber(components.pm10_score, 1)}; stress ${formatNumber(stress, 1)}${state.fallback ? " (documented fallback)" : ""}.`,
        ],
        evidence: [
          { label: "Status", value: `${state.label}${state.modelTime ? ` · model time ${state.modelTime}` : ""}` },
          { label: "Effect on ranking", value: "The same regional value applies to all zones, shifting every total equally." },
        ],
      };
    }
    case "sensors":
      return {
        status: "answered",
        title,
        summary: "No. The values are modelled Open-Meteo / CAMS estimates for one coordinate near campus (30.356° N, 76.367° E).",
        points: [
          AIR_QUALITY_LABEL,
          "No campus sensor is connected. An ESP32 PM node is listed as future scope only.",
          "Modelled PM is regional context and is not assigned independently to zones or cells.",
        ],
        evidence: [{ label: "Provider", value: environment?.provider || "Open-Meteo Air Quality API" }],
      };
    case "limitations":
      return {
        status: "answered",
        title,
        summary: "GreenPulse AI is a decision-support MVP. Its outputs indicate where to look first; they are not ground truth.",
        points: [
          "NDVI thresholds are project-calibrated, not universal ecological classes.",
          "Dynamic World land cover is a supporting ~10 m indicator, not building-level ground truth.",
          "Satellite data have finite spatial resolution; small features may be mixed within pixels.",
          "Sentinel-2 (seasonal) and Landsat (annual) series are separate sensors and are never merged.",
          "PM values are regional modelled estimates, identical for all zones.",
          "The official priority score is zone-level; 50 m cells show indicators only.",
          "A mapped cell is not a validated planting site; interventions need local ground review.",
          "No causal link between vegetation and pollution is claimed.",
        ],
        evidence: [],
      };
    case "species":
      return {
        ...unavailable(title, "Species recommendation and site validation are future-scope modules; no species, soil or ground-survey data is loaded."),
        summary: "Not answered: the loaded data cannot support a species or site recommendation.",
        evidence: [{ label: "What is available", value: "Mapped plantable potential per 50 m cell (an indicator that needs ground review)" }],
      };
    case "forecast":
      return {
        ...unavailable(title, "GreenPulse shows modelled past and current PM estimates only; it does not forecast air quality or compute an official AQI."),
        summary: "Not answered: GreenPulse does not forecast air quality.",
        evidence: [{ label: "What is available", value: "The latest 24-hour modelled PM2.5 / PM10 averages and PM stress" }],
      };
    default:
      return unavailable(title, null);
  }
}
